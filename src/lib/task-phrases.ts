/** Una frase al azar, distinta de la anterior si se indica. */
export function randomTaskPhrase(previous?: string): string {
  const pool = previous ? TASK_PHRASES.filter((p) => p !== previous) : TASK_PHRASES;
  return pool[Math.floor(Math.random() * pool.length)];
}
